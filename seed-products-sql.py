#!/usr/bin/env python3
"""
seed-products-sql.py — turn products.json into the SQL that seeds Supabase.

    python3 seed-products-sql.py

Writes ../fireandfaye-yoco-backend/docs/seed-products.sql, which you paste
into the Supabase SQL editor once, after supabase-products.sql.

Why generate SQL rather than insert over the API: the API needs the service
key, and that key must never leave Vercel. Pasting SQL into the dashboard
needs no key at all, and the file is reviewable before it runs.

Run again whenever products.json changes AHEAD of the database — which should
be never after the first seed, because from then on the database leads.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'fireandfaye-yoco-backend', 'docs', 'seed-products.sql')


def q(s):
    """Quote a string for SQL. Doubling the apostrophe is the whole trick, and
    these names are full of them — Gaia's Gift, Evil Eye's Embrace."""
    return "'" + str(s).replace("'", "''") + "'"


def jpeg_size(path):
    """Width and height from the JPEG's SOF marker. Same reader build.py uses —
    there is no image library on this machine."""
    with open(path, 'rb') as f:
        data = f.read()
    i = 2
    while i < len(data) - 9:
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            return (int.from_bytes(data[i + 7:i + 9], 'big'),
                    int.from_bytes(data[i + 5:i + 7], 'big'))
        i += 2 + int.from_bytes(data[i + 2:i + 4], 'big')
    return (900, 1200)


def main():
    products = json.load(open(os.path.join(HERE, 'products.json'), encoding='utf-8'))

    lines = [
        "-- fire&faye — seed the products tables from products.json",
        "--",
        "-- GENERATED by seed-products-sql.py. Run once, after supabase-products.sql.",
        "--",
        "-- Idempotent: re-running overwrites the product rows and rebuilds the image",
        "-- rows, so a half-finished run can simply be run again.",
        "",
        "begin;",
        "",
    ]

    lines.append("insert into public.products (id, name, category, description, price_cents, is_listed) values")
    rows = []
    for p in products:
        cents = round(float(p['price'].lstrip('R')) * 100)
        rows.append(f"  ({q(p['id'])}, {q(p['name'])}, {q(p['category'])}, "
                    f"{q(p['desc'])}, {cents}, true)")
    lines.append(",\n".join(rows))
    lines.append("on conflict (id) do update set")
    lines.append("  name = excluded.name, category = excluded.category,")
    lines.append("  description = excluded.description, price_cents = excluded.price_cents;")
    lines.append("")

    # Rebuilt wholesale rather than upserted: positions are the thing being
    # seeded, and a partial update would leave stale rows at old positions.
    lines.append("delete from public.product_images;")
    lines.append("")
    lines.append("insert into public.product_images (product_id, published_path, width, height, position) values")
    rows = []
    for p in products:
        for n, rel in enumerate(p['images'], start=1):
            w, h = jpeg_size(os.path.join(HERE, rel.lstrip('/')))
            rows.append(f"  ({q(p['id'])}, {q(rel)}, {w}, {h}, {n})")
    lines.append(",\n".join(rows) + ";")
    lines.append("")
    lines.append("commit;")
    lines.append("")
    lines.append(f"-- {len(products)} products, {sum(len(p['images']) for p in products)} images")

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))

    print(f"wrote {os.path.relpath(OUT, HERE)}")
    print(f"  {len(products)} products")
    print(f"  {sum(len(p['images']) for p in products)} images")


if __name__ == '__main__':
    main()
